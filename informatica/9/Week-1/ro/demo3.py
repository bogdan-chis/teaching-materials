a = 15
b = 4

print("Suma (a + b):", a + b)           # 19
print("Diferența (a - b):", a - b)      # 11
print("Produsul (a * b):", a * b)       # 60
print("Împărțirea reală (a / b):", a / b) # 3.75

# Operatori specifici (foarte des folosiți în algoritmi)
print("Câtul împărțirii (a // b):", a // b)  # 3 (de câte ori intră 4 în 15)
print("Restul împărțirii (a % b):", a % b)   # 3 (modulo)
print("Ridicarea la putere (a ** b):", a ** b) # 15 la puterea 4 (50625)